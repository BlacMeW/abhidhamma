new_lines = []
in_samuccaya = False
i = 0

while i < len(lines):
    line = lines[i]
    if line.strip().startswith("## သမုစ္စည်း"):
        in_samuccaya = True
    elif line.strip().startswith("## ပစ္စည်း"):
        in_samuccaya = False
        
    if in_samuccaya:
        match = re.match(r'^(\s*)-\s+(.*)$', line.rstrip())
        if match:
            indent = match.group(1)
            name = match.group(2).strip()
            
            has_child = False
            if i + 1 < len(lines):
                next_match = re.match(r'^(\s*)-\s+(.*)$', lines[i+1].rstrip())
                if next_match and len(next_match.group(1)) > len(indent):
                    has_child = True
                    
            if name in samuccaya_meanings and not has_child:
                new_lines.append(line)
                new_lines.append(f"{indent}  - {samuccaya_meanings[name]}\n")
            else:
                new_lines.append(line)
        else:
            new_lines.append(line)
    else:
        new_lines.append(line)
    i += 1

with open('concept_map.html', 'w', encoding='utf-8') as f:
    f.writelines(new_lines)

