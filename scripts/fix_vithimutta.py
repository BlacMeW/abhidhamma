new_lines = []
in_vithimutta = False
i = 0

while i < len(lines):
    line = lines[i]
    if line.strip().startswith("## ဝီထိမုတ္တ"):
        in_vithimutta = True
    elif line.strip().startswith("## သမုစ္စည်း"):
        in_vithimutta = False
        
    if in_vithimutta:
        match = re.match(r'^(\s*)-\s+(.*)$', line.rstrip())
        if match:
            indent = match.group(1)
            name = match.group(2).strip()
            
            # Remove (xxx) numbers if any for matching, though our dict uses exact for "လူ (၁)"
            name_clean = name
            
            has_child = False
            if i + 1 < len(lines):
                next_match = re.match(r'^(\s*)-\s+(.*)$', lines[i+1].rstrip())
                if next_match and len(next_match.group(1)) > len(indent):
                    has_child = True
                    
            if name_clean in vithimutta_meanings and not has_child:
                new_lines.append(line)
                new_lines.append(f"{indent}  - {vithimutta_meanings[name_clean]}\n")
            else:
                new_lines.append(line)
        else:
            new_lines.append(line)
    else:
        new_lines.append(line)
    i += 1

with open('concept_map.html', 'w', encoding='utf-8') as f:
    f.writelines(new_lines)

print("Vithimutta completely fixed")
