        const buttonContainer = document.getElementById('emotion-buttons');
        const resultContainer = document.getElementById('analysis-result');
        const emptyState = document.getElementById('empty-state');
        
        let currentActiveBtn = null;

        // Initialize Buttons
        Object.values(emotionData).forEach(data => {
            const btn = document.createElement('button');
            // Base styling based on Kusala/Akusala for subtle hints, or just use neutral with hover
            btn.className = `px-5 py-3 rounded-xl border-2 border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-700 dark:text-slate-200 font-semibold transition-all hover:border-${data.color}-400 hover:bg-${data.color}-50 dark:hover:bg-${data.color}-900/20 flex items-center gap-2`;
            btn.innerHTML = `<i class="fa-solid ${data.icon} text-${data.color}-500"></i> ${data.name}`;
            
            btn.onclick = () => selectEmotion(data.id, btn);
            buttonContainer.appendChild(btn);
        });

        function selectEmotion(id, btnElement) {
            const data = emotionData[id];
            if (!data) return;

            // Update active button state
            if (currentActiveBtn) {
                currentActiveBtn.classList.remove('ring-2', 'ring-offset-2', 'ring-offset-slate-50', 'dark:ring-offset-slate-900', 'border-transparent');
            }
            btnElement.classList.add('ring-2', 'ring-offset-2', 'ring-offset-slate-50', 'dark:ring-offset-slate-900', `ring-${data.color}-500`, 'border-transparent');
            currentActiveBtn = btnElement;

            // Hide empty state, show result
            emptyState.classList.add('hidden');
            resultContainer.classList.remove('hidden');
            
            // Re-trigger animation
            resultContainer.classList.remove('fade-in');
            void resultContainer.offsetWidth; // trigger reflow
            resultContainer.classList.add('fade-in');

            // Populate Data
            document.getElementById('emotion-name').textContent = data.name;
            document.getElementById('emotion-desc').textContent = data.desc;
            document.getElementById('citta-name').textContent = data.cittaName;

            const badge = document.getElementById('citta-type-badge');
            if (data.type === 'akusala') {
                badge.textContent = 'အကုသိုလ် (Akusala)';
                badge.className = 'px-3 py-1 rounded-full text-xs font-bold bg-red-100 text-red-700 dark:bg-red-900/30 dark:text-red-400 border border-red-200 dark:border-red-800';
            } else {
                badge.textContent = 'ကုသိုလ် (Kusala)';
                badge.className = 'px-3 py-1 rounded-full text-xs font-bold bg-emerald-100 text-emerald-700 dark:bg-emerald-900/30 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-800';
            }

            // Populate Cetasikas
            const cetasikaContainer = document.getElementById('cetasika-container');
            cetasikaContainer.innerHTML = ''; // clear

            if (data.cetasikaCount) {
                const countDiv = document.createElement('div');
                countDiv.className = "text-sm text-slate-600 dark:text-slate-400 mb-3 w-full bg-slate-100 dark:bg-slate-800/50 p-3 rounded-lg border border-slate-200 dark:border-slate-700 font-medium flex items-center gap-2";
                countDiv.innerHTML = `<i class="fa-solid fa-layer-group text-slate-400"></i> ယှဉ်တွဲသော စေတသိက် စုစုပေါင်း - <span class="text-slate-900 dark:text-slate-100 font-bold">${data.cetasikaCount}</span>`;
                cetasikaContainer.appendChild(countDiv);
            }

            data.cetasikasGroups.forEach(group => {
                const groupTitle = document.createElement('div');
                groupTitle.className = "w-full text-[11px] font-bold text-slate-500 mt-3 mb-2 uppercase tracking-wider pl-1";
                groupTitle.textContent = group.groupName;
                cetasikaContainer.appendChild(groupTitle);

                const groupContainer = document.createElement('div');
                groupContainer.className = "flex flex-wrap gap-2 w-full mb-2";

                group.items.forEach(cet => {
                    const badgeColor = data.type === 'akusala' && group.groupName.includes("အကုသိုလ်")
                        ? 'bg-rose-50 text-rose-700 border-rose-200 dark:bg-rose-900/20 dark:text-rose-300 dark:border-rose-800' 
                        : (data.type === 'kusala' && group.groupName.includes("သောဘဏ")
                            ? 'bg-teal-50 text-teal-700 border-teal-200 dark:bg-teal-900/20 dark:text-teal-300 dark:border-teal-800'
                            : 'bg-slate-50 text-slate-700 border-slate-200 dark:bg-slate-800/80 dark:text-slate-300 dark:border-slate-700');
                    
                    const cBadge = document.createElement('div');
                    cBadge.className = `px-3 py-2 rounded-lg border text-sm flex flex-col ${badgeColor}`;
                    cBadge.innerHTML = `<span class="font-bold">${cet.name}</span><span class="text-[11px] opacity-80 mt-0.5 leading-tight">${cet.desc}</span>`;
                    groupContainer.appendChild(cBadge);
                });
                cetasikaContainer.appendChild(groupContainer);
            });
        }
